"""
Elemental and Charge Balance Verification Engine.

This module implements Section 4.5 and Table 4 of the framework:
Automated chemical formula parsing and stoichiometric balance validation
to guarantee conservation of mass (C, H, O, N, P, S, etc.) and charge across
reaction hypotheses generated by language models or literature extraction.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple


@dataclass
class BalanceResult:
    """Detailed outcome of stoichiometric and charge balance validation."""
    reaction_str: str
    is_balanced: bool
    lhs_atoms: Dict[str, int]
    rhs_atoms: Dict[str, int]
    atom_deltas: Dict[str, int]
    lhs_charge: int
    rhs_charge: int
    charge_delta: int
    imbalances: List[str] = field(default_factory=list)
    verdict: str = "Balanced"

    def summary(self) -> str:
        """Return a formatted scientific summary suitable for audit tables."""
        if self.is_balanced:
            atoms_str = ", ".join(f"{k}: {v}" for k, v in sorted(self.lhs_atoms.items()))
            return f"Balanced (Net atoms conserved: {atoms_str}; Charge: {self.lhs_charge})"
        
        reasons = "; ".join(self.imbalances)
        return f"Imbalanced ({reasons})"


def parse_formula(formula: str) -> Tuple[Dict[str, int], int]:
    """
    Parse a chemical formula string into atom counts and net formal charge.

    Supports:
      - Simple formulas: C6H12O6, H2O, CO2, NH3, CH4
      - Parentheses: Ca(OH)2, (NH4)2SO4, Fe(NO3)3
      - Charges: H+, OH-, SO4[2-], Fe[3+], Fe+2, Ca++, e-
    """
    clean_formula = formula.strip()
    if not clean_formula:
        return {}, 0

    # Handle special case: electron
    if clean_formula in ("e-", "e^-", "e"):
        return {}, -1

    # Extract trailing charge if present
    charge = 0
    clean_formula = formula.strip()
    
    # 1. Bracketed charges: [2-], [3+], [+], [-], [2+]
    m = re.search(r'\[([0-9]*[\+\-]|\+|-+)\]$', clean_formula)
    # 2. Superscript charges: ^2-, ^3+, ^-, ^+
    if not m:
        m = re.search(r'\^([0-9]*[\+\-]|\+|-+)$', clean_formula)
    # 3. Direct trailing sign(s): +, -, ++, --, +++
    if not m:
        m = re.search(r'([\+\-]+)$', clean_formula)

    if m:
        charge_str = m.group(1)
        clean_formula = clean_formula[:m.start()].strip()
        
        if charge_str == '+':
            charge = 1
        elif charge_str == '-':
            charge = -1
        elif charge_str.endswith('+'):
            val = charge_str[:-1]
            charge = int(val) if val else 1
        elif charge_str.endswith('-'):
            val = charge_str[:-1]
            charge = -int(val) if val else -1
        elif set(charge_str) == {'+'}:
            charge = len(charge_str)
        elif set(charge_str) == {'-'}:
            charge = -len(charge_str)

    # Recursive sub-group parser for nested brackets/parentheses
    def parse_tokens(tok_str: str) -> Dict[str, int]:
        counts: Dict[str, int] = {}
        # Expand parenthesized groups: (Formula)multiplier
        pattern = re.compile(r'\(([^()]+)\)(\d*)')
        while True:
            m = pattern.search(tok_str)
            if not m:
                break
            sub_formula = m.group(1)
            mult = int(m.group(2)) if m.group(2) else 1
            sub_counts = parse_tokens(sub_formula)
            # Reconstruct string by replacing the group with equivalent flat formula
            flat = "".join(f"{k}{v * mult}" for k, v in sub_counts.items())
            tok_str = tok_str[:m.start()] + flat + tok_str[m.end():]

        # Extract [Element][Count]
        elem_pattern = re.compile(r'([A-Z][a-z]*)(\d*)')
        for el_match in elem_pattern.finditer(tok_str):
            element = el_match.group(1)
            count_str = el_match.group(2)
            count = int(count_str) if count_str else 1
            counts[element] = counts.get(element, 0) + count

        return counts

    atom_counts = parse_tokens(clean_formula)
    return atom_counts, charge


def parse_reaction_side(side_str: str) -> Tuple[Dict[str, int], int, List[Tuple[float, str]]]:
    """Parse one side of a reaction into total atom counts, total charge, and species list."""
    total_atoms: Dict[str, int] = {}
    total_charge = 0
    species_list: List[Tuple[float, str]] = []

    # Split terms by '+' that are not inside brackets
    terms = [t.strip() for t in re.split(r'\s+\+\s+', side_str.strip()) if t.strip()]

    for term in terms:
        # Match leading stoichiometric coefficient (integer or float/fraction)
        coeff_match = re.match(r'^(\d+(?:\.\d+)?|\d+/\d+)\s*(.*)$', term)
        if coeff_match and coeff_match.group(2):
            raw_coeff = coeff_match.group(1)
            formula = coeff_match.group(2).strip()
            if '/' in raw_coeff:
                num, denom = raw_coeff.split('/')
                coeff = float(num) / float(denom)
            else:
                coeff = float(raw_coeff)
        else:
            coeff = 1.0
            formula = term

        atoms, charge = parse_formula(formula)
        species_list.append((coeff, formula))

        for el, count in atoms.items():
            total_atoms[el] = total_atoms.get(el, 0) + int(round(count * coeff))

        total_charge += int(round(charge * coeff))

    return total_atoms, total_charge, species_list


def check_balance(reaction_str: str) -> BalanceResult:
    """
    Validate elemental and charge conservation for a chemical reaction equation.

    Parameters:
      reaction_str: String formatted like 'C6H12O6 -> 2 C2H5OH + 2 CO2'
                    or 'S + 2 e- -> S[2-]'

    Returns:
      BalanceResult containing verification status and atom/charge differences.
    """
    # Detect reaction arrow
    arrow_pattern = re.compile(r'\s*(?:<==>|<=>|-->|->|=>|=)\s*')
    parts = arrow_pattern.split(reaction_str.strip())
    if len(parts) != 2:
        return BalanceResult(
            reaction_str=reaction_str,
            is_balanced=False,
            lhs_atoms={},
            rhs_atoms={},
            atom_deltas={},
            lhs_charge=0,
            rhs_charge=0,
            charge_delta=0,
            imbalances=["Invalid reaction format (no directional arrow found)"],
            verdict="Error: Invalid Syntax"
        )

    lhs_str, rhs_str = parts[0], parts[1]
    lhs_atoms, lhs_charge, _ = parse_reaction_side(lhs_str)
    rhs_atoms, rhs_charge, _ = parse_reaction_side(rhs_str)

    all_elements = sorted(set(lhs_atoms.keys()) | set(rhs_atoms.keys()))
    atom_deltas: Dict[str, int] = {}
    imbalances: List[str] = []

    for el in all_elements:
        l_cnt = lhs_atoms.get(el, 0)
        r_cnt = rhs_atoms.get(el, 0)
        delta = r_cnt - l_cnt
        atom_deltas[el] = delta
        if delta != 0:
            direction = "surplus" if delta > 0 else "deficit"
            imbalances.append(f"{el} {direction} of {abs(delta)} ({l_cnt} -> {r_cnt})")

    charge_delta = rhs_charge - lhs_charge
    if charge_delta != 0:
        imbalances.append(f"Charge imbalance: LHS={lhs_charge:+d}, RHS={rhs_charge:+d} (Δ={charge_delta:+d})")

    is_balanced = len(imbalances) == 0
    verdict = "Balanced" if is_balanced else f"Imbalanced: {', '.join(imbalances)}"

    return BalanceResult(
        reaction_str=reaction_str,
        is_balanced=is_balanced,
        lhs_atoms=lhs_atoms,
        rhs_atoms=rhs_atoms,
        atom_deltas=atom_deltas,
        lhs_charge=lhs_charge,
        rhs_charge=rhs_charge,
        charge_delta=charge_delta,
        imbalances=imbalances,
        verdict=verdict
    )
